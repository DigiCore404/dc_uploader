'use strict';
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),assert=require('node:assert/strict');
const source=fs.readFileSync(path.join(__dirname,'../webui/app.js'),'utf8');
const requests=[],nodes=new Map();let refreshes=0;
const $=id=>{if(!nodes.has(id))nodes.set(id,{hidden:false,textContent:'',scrollHeight:0,scrollTop:0,clientHeight:0,classList:{toggle(){}},focus(){},addEventListener(event,fn){this[event]=fn;}});return nodes.get(id);};
const context=vm.createContext({$,api:()=>new Promise(resolve=>requests.push(resolve)),clearTimeout,setTimeout,refreshActivity:async()=>{refreshes++;},toast:()=>{},renderHashProgress:()=>{},showJobDetails:()=>{},stages:{},statuses:{completed:'Completed',running:'Uploading'}});
const start=source.indexOf('function closeJobDetails()'),end=source.indexOf("$('history-filter')",start);
vm.runInContext('let activeJob=null,pollTimer=null,selectedJob=null,jobRequest=0;'+source.slice(start,end),context);
const run=code=>vm.runInContext(code,context);
const tick=()=>new Promise(resolve=>setImmediate(resolve));
const job=id=>({id,name:id,status:'completed',logs:[],stage:'completed'});
(async()=>{
  run("openJob('first')");
  assert.equal($('upload-history').hidden,true);
  $('back-activity').click();
  assert.equal($('upload-history').hidden,false);
  requests.shift()(job('first'));await tick();
  assert.equal($('job-current').hidden,true,'A late response must not reopen details after Back');
  run("openJob('old');openJob('new')");
  requests.shift()(job('old'));await tick();
  assert.equal($('job-current').hidden,true,'Stale selection must not replace the new one');
  requests.shift()(job('new'));await tick();
  assert.equal($('job-title').textContent,'new');assert.equal($('job-current').hidden,false);
  assert.equal($('upload-history').hidden,true,'Completion refresh must keep the selected details visible');
  run('closeJobDetails()');assert.equal($('upload-history').hidden,false);assert.equal($('job-navigation').hidden,true);
  assert.match(source,/function page\(name\) \{ closeJobDetails\(\);/,'Sidebar navigation must return to the overview');
  assert.ok(refreshes>=2);
  console.log('Activity navigation: Back, sidebar reset and late-response races passed.');
})().catch(error=>{console.error(error);process.exitCode=1;});
